"""Minimal API/UI prototype for predictive deployment risk analysis.

Important: the included model is a synthetic-data demonstration only. It is not
validated for production decisions or for dissertation conclusions.
"""
from pathlib import Path
from typing import Any
import json
import joblib
import numpy as np
import httpx
from fastapi import FastAPI, HTTPException
from fastapi.responses import HTMLResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field
from scripts.train_demo_model import train_and_save

ROOT = Path(__file__).resolve().parents[1]
MODEL_PATH = ROOT / "artifacts" / "demo_model.joblib"
META_PATH = ROOT / "artifacts" / "demo_model_metadata.json"
ARTIFACTS_PATH = ROOT / "artifacts"
IMPORTED_CI_REPORT_PATH = ARTIFACTS_PATH / "dashboard_latest_ci_report.json"
GENERATED_CI_REPORT_PATH = ARTIFACTS_PATH / "ci-risk-report.json"
# Public read-only feed published by the CI workflow to the ci-reports branch.
# It contains only the generated evidence JSON; no token is embedded in the dashboard.
PUBLIC_CI_REPORT_URL = "https://raw.githubusercontent.com/hardikgenie/deployment-risk-predictor/ci-reports/latest-ci-risk-report.json"
STATIC_PATH = ROOT / "static"

if not MODEL_PATH.exists():
    train_and_save()
_model_bundle = joblib.load(MODEL_PATH)
_model = _model_bundle["model"]
FEATURES = _model_bundle["features"]
_metadata = json.loads(META_PATH.read_text(encoding="utf-8")) if META_PATH.exists() else {}

app = FastAPI(title="Deployment Risk Predictor", version="0.1.0", description="Research prototype using synthetic demo data.")
app.mount("/static", StaticFiles(directory=str(STATIC_PATH)), name="static")


class DeploymentFeatures(BaseModel):
    changed_files: int = Field(12, ge=0, le=1000)
    lines_added: int = Field(350, ge=0, le=100000)
    lines_deleted: int = Field(100, ge=0, le=100000)
    test_failure_count: int = Field(0, ge=0, le=1000)
    test_pass_rate: float = Field(98.0, ge=0, le=100)
    code_quality_issues: int = Field(3, ge=0, le=10000)
    security_findings: int = Field(0, ge=0, le=1000)
    pipeline_retries: int = Field(0, ge=0, le=1000)
    recent_deploy_failures: int = Field(0, ge=0, le=1000)
    config_change: int = Field(0, ge=0, le=1)
    dependency_change: int = Field(0, ge=0, le=1)


class CIReportImport(BaseModel):
    """Shape of the JSON report generated by the GitHub Actions evidence step."""
    schema_version: int = 1
    run: dict[str, Any]
    pipeline: dict[str, Any]
    change_signals: dict[str, Any]
    model_output: dict[str, Any]
    decision: dict[str, Any]
    warnings: list[str] = Field(default_factory=list)
    feature_sources_measured: dict[str, bool] = Field(default_factory=dict)
    features_sent_to_demo_model: dict[str, Any] = Field(default_factory=dict)


@app.get("/", response_class=HTMLResponse)
def index():
    html_path = STATIC_PATH / "index.html"
    return HTMLResponse(html_path.read_text(encoding="utf-8"))


@app.get("/health")
def health():
    return {"status": "ok", "model_type": "RandomForestClassifier", "data_type": _metadata.get("data_type", "unknown")}


def explain_drivers(f: DeploymentFeatures):
    drivers = []
    if f.test_failure_count > 0: drivers.append("Test failures are present")
    if f.test_pass_rate < 90: drivers.append("Test pass rate is below 90%")
    if f.security_findings > 0: drivers.append("Security findings are present")
    if f.recent_deploy_failures > 0: drivers.append("Recent deployment failures are reported")
    if f.config_change: drivers.append("Configuration change is flagged")
    if f.dependency_change: drivers.append("Dependency change is flagged")
    if f.changed_files > 30: drivers.append("Large number of changed files")
    if f.code_quality_issues > 10: drivers.append("Elevated static-analysis findings")
    if f.pipeline_retries > 2: drivers.append("Multiple pipeline retries")
    if not drivers: drivers.append("No obvious high-severity flags in the entered demo features")
    return drivers[:4]


@app.post("/predict")
def predict(features: DeploymentFeatures):
    try:
        row = np.array([[getattr(features, name) for name in FEATURES]], dtype=float)
        probability = float(_model.predict_proba(row)[0][1])
    except Exception as exc:
        raise HTTPException(status_code=500, detail="Prediction failed. Check the local model artifact.") from exc
    category = "HIGH" if probability >= 0.67 else "MEDIUM" if probability >= 0.34 else "LOW"
    return {
        "risk_probability": round(probability, 4),
        "risk_percent": round(probability * 100, 1),
        "risk_category": category,
        "drivers": explain_drivers(features),
        "data_notice": "Synthetic-data demo model only. Do not use this output for production release decisions or as a dissertation finding.",
    }

@app.get("/api/ci/latest")
def latest_ci_report():
    """Return the latest CI evidence known to this local dashboard.

    GitHub Actions runs on a separate hosted runner, so its report must either
    be generated locally or imported from the downloaded workflow artifact.
    """
    # When the public CI feed exists, the dashboard can refresh the latest
    # workflow report directly. Fall back to a locally generated/imported report
    # for offline demos or private repositories.
    if PUBLIC_CI_REPORT_URL:
        try:
            response = httpx.get(PUBLIC_CI_REPORT_URL, timeout=1.5, follow_redirects=True)
            if response.status_code == 200:
                remote_report = response.json()
                if isinstance(remote_report, dict) and all(
                    key in remote_report for key in ("run", "pipeline", "change_signals", "model_output", "decision")
                ):
                    return {"available": True, "source": "github_actions_latest_report", "report": remote_report}
        except (httpx.HTTPError, ValueError):
            # The raw URL may return 404 until the first publishing workflow run.
            pass

    candidates = [
        (source, path)
        for source, path in (
            ("imported_github_actions_artifact", IMPORTED_CI_REPORT_PATH),
            ("local_ci_report", GENERATED_CI_REPORT_PATH),
        )
        if path.is_file()
    ]
    if candidates:
        source, path = max(candidates, key=lambda item: item[1].stat().st_mtime)
        try:
            report = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise HTTPException(status_code=500, detail=f"Stored CI report is not readable: {path.name}") from exc
        return {"available": True, "source": source, "report": report}
    return {
        "available": False,
        "message": "No CI report has been loaded yet. Open the latest GitHub Actions run, download the ci-risk-evidence artifact, unzip it, then import ci-risk-report.json here.",
    }


@app.post("/api/ci/import")
def import_ci_report(payload: CIReportImport):
    """Store a CI evidence JSON uploaded through the dashboard UI."""
    ARTIFACTS_PATH.mkdir(parents=True, exist_ok=True)
    data = payload.model_dump(mode="json")
    IMPORTED_CI_REPORT_PATH.write_text(json.dumps(data, indent=2), encoding="utf-8")
    return {"available": True, "source": "imported_github_actions_artifact", "message": "CI report imported into the dashboard."}

